"""Lossless HTTP representations for direct-URL browser deployment.

This is not a pack codec: the logical URL and decoded asset identity never
change. Generated bytes live only in the caller's disjoint staging directory.
Client-encoded pack blobs and media are not nested inside another codec; an
identity pack blob is ordinary content and may be delivered compressed.
"""
from __future__ import annotations

from dataclasses import dataclass
import gzip
import hashlib
from pathlib import Path, PurePosixPath
import zlib

from .paths import output_path

try:
    import brotli
except ImportError:  # gzip remains available without optional dependencies
    brotli = None

COMPRESSIBLE = frozenset({".glb", ".gltf", ".rgba8", ".bin", ".wasm",
    ".json", ".js", ".mjs", ".css", ".html", ".txt", ".svg", ".wgsl", ".glsl", ".map"})
MIN_BYTES = 1024
BROTLI_QUALITY = 5
BROTLI_LGWIN = 22
GZIP_LEVEL = 6
ENCODED_SUFFIXES = frozenset({".gz", ".br", ".gzz", ".brz", ".zip", ".zst",
    ".png", ".jpg", ".jpeg", ".webp", ".ktx2", ".ogg", ".mp3", ".avif", ".woff", ".woff2"})
# Content-addressed blobs carry no media suffix, so compressed media is also
# recognised by its signature: gzip, zip, zstd, PNG, Ogg, JPEG, KTX2.
ENCODED_SIGNATURES = (b"\x1f\x8b", b"PK\x03\x04", b"\x28\xb5\x2f\xfd", b"\x89PNG", b"OggS",
    b"\xff\xd8\xff", b"\xabKTX 20")


def sha256(body):
    return hashlib.sha256(body).hexdigest()


def generation_reason(logical, raw):
    path = PurePosixPath(logical)
    if path.suffix.lower() in ENCODED_SUFFIXES or raw.startswith(ENCODED_SIGNATURES):
        return "already-encoded-payload"
    if path.suffix.lower() not in COMPRESSIBLE:
        return "format-not-selected"
    if len(raw) < MIN_BYTES:
        return "below-minimum-size"
    return None


@dataclass(frozen=True)
class Representation:
    source: Path
    raw_source: Path
    encoding: str
    body: bytes
    decoded_bytes: int
    decoded_sha256: str
    invalid_sidecars: tuple
    generated: bool
    generation_skipped: str | None

    @property
    def manifest_fields(self):
        return {"source": str(self.source), "sourceRaw": str(self.raw_source),
                "contentEncoding": self.encoding, "bytes": len(self.body),
                "decodedBytes": self.decoded_bytes, "sha256": sha256(self.body),
                "decodedSha256": self.decoded_sha256, "deliveryMode": "fixed",
                "requiredAcceptEncoding": None if self.encoding == "identity" else self.encoding,
                "metadata": {"moly-decoded-bytes": str(self.decoded_bytes),
                             "moly-decoded-sha256": self.decoded_sha256},
                "generatedRepresentation": self.generated}


def policy_profile(mode, generate=True):
    return {"schemaVersion": 1, "mode": mode, "deliveryMode": "fixed", "generateMissing": generate,
            "minimumBytes": MIN_BYTES, "minimumSavingBytes": 64,
            "minimumSavingRatio": 0.01,
            "gzip": {"level": GZIP_LEVEL, "mtime": 0, "zlib": zlib.ZLIB_RUNTIME_VERSION},
            "brotli": None if brotli is None else {"quality": BROTLI_QUALITY,
                "lgwin": BROTLI_LGWIN, "version": getattr(brotli, "__version__", "unknown")},
            "extensions": sorted(COMPRESSIBLE), "encodedSignatures": [signature.hex() for signature in ENCODED_SIGNATURES]}


def choose_representation(source, logical, cache_dir, *, mode="best", generate=True):
    if mode not in {"identity", "gzip", "best"}:
        raise ValueError("unknown HTTP delivery encoding policy")
    source = Path(source).resolve(strict=True)
    raw = source.read_bytes()
    raw_hash = sha256(raw)
    selected, encoding, body, generated = source, "identity", raw, False
    invalid = []
    skipped = generation_reason(logical, raw)
    decoders = {"gzip": gzip.decompress}
    if brotli is not None:
        decoders["br"] = brotli.decompress
    kinds = [] if mode == "identity" else ["gzip"] + (["br"] if mode == "best" and brotli is not None else [])
    # Existing sidecars remain useful (e.g. engine WASM compressed at q11).
    # Never add an outer encoding to a payload already encoded for the client.
    if skipped == "already-encoded-payload":
        kinds = []
    for kind in kinds:
        candidate = Path(str(source) + (".gz" if kind == "gzip" else ".br"))
        if candidate.is_file():
            compressed = candidate.read_bytes()
            try:
                valid = decoders[kind](compressed) == raw
            except Exception:
                valid = False
            if not valid:
                invalid.append({"path": logical, "source": str(candidate), "encoding": kind})
            elif (len(raw) - len(compressed) >= max(64, (len(raw) + 99) // 100)
                  and len(compressed) < len(body)):
                selected, encoding, body = candidate, kind, compressed
        if not generate or skipped is not None:
            continue
        compressed = (gzip.compress(raw, compresslevel=GZIP_LEVEL, mtime=0) if kind == "gzip"
                      else brotli.compress(raw, quality=BROTLI_QUALITY, lgwin=BROTLI_LGWIN))
        # Reject growth and insignificant savings, including incompressible BINs.
        if len(raw) - len(compressed) < max(64, (len(raw) + 99) // 100) or len(compressed) >= len(body):
            continue
        if decoders[kind](compressed) != raw:
            raise ValueError("generated HTTP representation changed decoded asset bytes")
        selected, encoding, body, generated = None, kind, compressed, True
    if selected is not None:
        generated = False
    else:
        digest = sha256(body)
        target = output_path(cache_dir, digest[:2] + "/" + digest + (".gz" if encoding == "gzip" else ".br"))
        target.parent.mkdir(parents=True, exist_ok=True)
        try:
            with target.open("xb") as stream:
                stream.write(body)
        except FileExistsError:
            if target.read_bytes() != body:
                raise ValueError("generated representation cache contains conflicting bytes")
        selected = target
    return Representation(selected, source, encoding, body, len(raw), raw_hash,
                          tuple(invalid), generated, skipped)
